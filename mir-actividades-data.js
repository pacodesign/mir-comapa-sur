function prioridad(a) {
  var d = diasRestantes(a.fechaLimite);
  if (d < 0)   return 'vencida';
  if (d <= 7)  return 'alta';
  if (d <= 14) return 'media';
  return 'normal';
}

function fechaEnvio(a) {
  if (a.historial && a.historial.length > 0) {
    var entry = a.historial.find(function(h) {
      return (h.accion || '').toLowerCase().includes('envi');
    });
    if (entry && entry.fecha) return entry.fecha;
  }
  return a.ultimaActualizacion || a.fechaLimite || '—';
}

